import asyncio, pathlib
from playwright.async_api import async_playwright
ROOT=pathlib.Path('/workspace/dogzy-game'); SC=ROOT/'screens'; URL=(ROOT/'index.html').as_uri()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
        pg=await ctx.new_page(); errs=[]
        pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('console',lambda m: m.type=='error' and errs.append(m.text))
        await pg.goto(URL); await pg.evaluate('localStorage.clear()'); await pg.reload(); await pg.wait_for_timeout(800)
        await pg.screenshot(path=str(SC/'01-board.png'))
        # wheel 1 -> force 3 (4 spaces => index 4 building)
        await pg.evaluate('DZ.force.w1=3; DZ.force.w2=4; DZ.force.chance=2')
        await pg.click('#btnSpin'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(SC/'02-wheel-before.png'))
        await pg.click('#go'); await pg.wait_for_timeout(4000)
        await pg.screenshot(path=str(SC/'03-wheel-result.png'))
        await pg.click('#go'); await pg.wait_for_timeout(1250)
        await pg.screenshot(path=str(SC/'04-board-moved.png'))
        await pg.wait_for_timeout(700); await pg.click('#go'); await pg.wait_for_timeout(4000)
        await pg.screenshot(path=str(SC/'05-second-wheel.png'))
        await pg.click('#go'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=str(SC/'06-building-card.png'))
        await pg.click('#ok'); await pg.wait_for_timeout(300); await pg.screenshot(path=str(SC/'07-building-done.png'))
        await pg.click('#ok'); await pg.wait_for_timeout(500)
        await pg.screenshot(path=str(SC/'08-chance-card.png'))
        await pg.click('#ok'); await pg.wait_for_timeout(600)
        st=await pg.evaluate('JSON.stringify(DZ.state())'); print('state after turn',st)
        # hidden object
        await pg.evaluate('void DZ.hidden()'); await pg.wait_for_timeout(800)
        await pg.screenshot(path=str(SC/'09-hidden-object.png'))
        zones=await pg.query_selector_all('.zone')
        print('zones',len(zones))
        for z in zones[:5]:
            await z.scroll_into_view_if_needed(); await z.click()
        await pg.wait_for_timeout(300)
        await pg.evaluate("document.querySelector('#hs').scrollLeft=0")
        await pg.screenshot(path=str(SC/'10-hidden-object-progress.png'))
        for z in zones[5:]:
            await z.scroll_into_view_if_needed(); await z.click()
        await pg.wait_for_timeout(900)
        await pg.screenshot(path=str(SC/'11-hidden-object-win.png'))
        await pg.click('#ok'); await pg.wait_for_timeout(300)
        await pg.click('#btnLevels'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(SC/'12-levels.png')); await pg.click('#ok')
        # quiz
        await pg.evaluate("(()=>{const s=DZ.state(); s.pos=5; localStorage.setItem('dogzy-adoleschiant-v1', JSON.stringify(s));})()")
        await pg.reload(); await pg.wait_for_timeout(600)
        st2=await pg.evaluate('JSON.stringify(DZ.state())'); print('reloaded state',st2)
        await pg.evaluate('DZ.force.w1=0; DZ.force.w2=2'); await pg.click('#btnSpin'); await pg.wait_for_timeout(300)
        await pg.click('#go'); await pg.wait_for_timeout(3900); await pg.click('#go'); await pg.wait_for_timeout(1500)
        await pg.click('#go'); await pg.wait_for_timeout(3900); await pg.click('#go'); await pg.wait_for_timeout(400)
        await pg.screenshot(path=str(SC/'13-quiz.png'))
        for k in range(3):
            await pg.click('.opts .btn >> nth=1'); await pg.wait_for_timeout(1100)
        await pg.screenshot(path=str(SC/'14-quiz-result.png')); await pg.click('#ok'); await pg.wait_for_timeout(300)
        print('state after quiz', await pg.evaluate('JSON.stringify(DZ.state())'))
        # debug waypoint overlay full board (desktop)
        d=await b.new_page(viewport={'width':1536,'height':1100})
        await d.goto(URL+'?debug'); await d.wait_for_timeout(800)
        await d.screenshot(path=str(SC/'15-waypoints-debug-desktop.png'))
        m=await b.new_page(viewport={'width':390,'height':844})
        await m.goto(URL+'?debug'); await m.wait_for_timeout(800)
        await m.screenshot(path=str(SC/'16-waypoints-debug-mobile.png'))
        print('errors',errs)
        await b.close()
asyncio.run(main())
